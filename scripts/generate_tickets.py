#!/usr/bin/env python3
"""
pawmate_tickets.md を 1チケット1ファイルに分割するスクリプト。
pawmate/tickets/{in-progress,todo,done,archive}/ に出力する。
"""
import os
import textwrap

BASE = os.path.join(os.path.dirname(__file__), "..", "tickets")

DIRS = [
    f"{BASE}/in-progress",
    f"{BASE}/todo",
    f"{BASE}/done",
    f"{BASE}/archive/20260603-single-file",
]

for d in DIRS:
    os.makedirs(d, exist_ok=True)

# ── ヘルパー ──────────────────────────────────────────────────────────────────

def write(folder, filename, content):
    path = os.path.join(BASE, folder, filename)
    with open(path, "w") as f:
        f.write(textwrap.dedent(content).lstrip())
    print(f"  wrote {folder}/{filename}")

